"""Generate the game catalogue and player reference. Uses Python's standard library only."""
import json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
data=json.loads((root/'Tools/recipe-catalogue.json').read_text())
raw,recipes=data['ingredients'],data['recipes']
assert len(recipes)==400 and len(raw)==35
ids=[x['id'] for x in raw+recipes]
assert len(ids)==len(set(ids))
known=set(x['id'] for x in raw)
for r in recipes:
    assert r['points']>0 and r['needs']
    for need in r['needs']:assert need['units']>0 and set(need['any'])<=known
    known.add(r['id'])
quote=lambda s:json.dumps(s,ensure_ascii=False)
lines=['// Generated by Tools/generate_catalogue.py; edit Tools/recipe-catalogue.json.', 'using System.Text;', '', 'namespace SpinningFeast', '{', '    public enum FoodKind', '    {', '        '+', '.join(ids)+', Count', '    }', '    public enum MealShape { Rice, Noodle, Soup, StirFry, Fried, Dumpling, Bread, Salad, Dessert, RiceBall, Gratin, Flatbread, Sandwich, Burger, Omelette, Cream }', '    public static class Cookbook', '    {', f'        public const int RawCount = {len(raw)};', '        public const int KindCount = (int)FoodKind.Count;', '        public static readonly string[] RawNames = {'+','.join(quote(x['name']) for x in raw)+'};', '        public static readonly Recipe[] All = {']
for r in recipes:
    needs=', '.join('R('+str(n['units'])+','+','.join('FoodKind.'+x for x in n['any'])+')' for n in r['needs'])
    lines.append(f'            new Recipe(FoodKind.{r["id"]}, {quote(r["name"])}, {r["points"]}, {quote("|".join(r["aliases"]))}, {needs}) {{ Shape = MealShape.{r["shape"]} }},')
lines+=['        };', '''        static Requirement R(int units, params FoodKind[] any) { return new Requirement(units, any); }
        public static string Normalize(string s)
        {
            var b = new StringBuilder();
            foreach (char c in (s ?? "").Normalize(NormalizationForm.FormKC).ToLowerInvariant())
                if (!char.IsWhiteSpace(c) && c != '-' && c != '_') b.Append(c);
            return b.ToString();
        }
        public static int Find(string name)
        {
            string n = Normalize(name);
            for (int i = 0; i < All.Length; i++)
            {
                if (Normalize(All[i].Name) == n) return i;
                foreach (string alias in All[i].Aliases) if (Normalize(alias) == n) return i;
            }
            return -1;
        }
    }
}''']
(root/'Assets/SpinningFeast/Core/Catalogue.cs').write_text('\n'.join(lines)+'\n')
names={x['id']:x['name'] for x in raw+recipes}
md=[f'# レシピ一覧：{len(recipes)}種類', '', '材料は1人前の必要数。「／」は代用候補。Enterで可能な最大数を一括調理し、得点×人前を獲得する。', '完成料理は誰が作ったものでも次の料理に使える。前半200種はレシピ順・材料・得点・発見セーブを維持。後半200種は実在する料理名に差し替えた。食材は従来と同じ35種類。', '調味料や麺の種類などを共通化したゲーム用の簡略レシピであり、実際の料理手順ではない。', '', '## 食材：35種類', '', '、'.join(x['name'] for x in raw), '', '## 料理', '', '| No. | 料理名 | 英字入力 | 1人前の材料 | 得点 |', '|---:|---|---|---|---:|']
for i,r in enumerate(recipes):
    alias=next(a for a in r['aliases'] if a.isascii())
    needs='＋'.join(('（'+'／'.join(names[k] for k in n['any'])+'）' if len(n['any'])>1 else names[n['any'][0]])+f'×{n["units"]}' for n in r['needs'])
    md.append(f'| {i+1} | {r["name"]} | `{alias}` | {needs} | {r["points"]} |')
(root/'Docs/RecipeCatalogue.md').write_text('\n'.join(md)+'\n')
print(f'Generated {len(raw)} ingredients and {len(recipes)} recipes.')
